#!/usr/bin/env python3
"""Lumo Kart's deterministic, no-network procedural 3D asset factory.

An AI can propose a JSON specification, but geometry and exported GLB are
generated by audited code. This is not a trained text-to-3D neural model.
Usage:
  python3 tools/ai3d_factory.py --spec tools/ai3d/specs/crystal_cavern.json --output-dir build/ai3d
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import re
import struct
import sys

IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]{2,47}$")
MAX_ASSET_BYTES = 6_000_000


def validate_spec(value: object) -> dict:
    if not isinstance(value, dict):
        raise ValueError("Asset specification must be a JSON object")
    required = {"asset_id", "recipe", "seed", "height_m", "radius_m",
                "count", "max_triangles"}
    if set(value) != required:
        raise ValueError("Missing or unapproved specification fields")
    if not isinstance(value["asset_id"], str) or not IDENTIFIER.fullmatch(value["asset_id"]):
        raise ValueError("Invalid asset_id")
    if value["recipe"] != "crystal_cluster":
        raise ValueError("Only reviewed crystal_cluster recipe is authorized")
    if type(value["seed"]) is not int or not 0 <= value["seed"] <= 2**31 - 1:
        raise ValueError("Seed must be a bounded integer")
    if type(value["count"]) is not int or not 2 <= value["count"] <= 16:
        raise ValueError("Cluster count is out of bounds")
    if type(value["max_triangles"]) is not int or not 72 <= value["max_triangles"] <= 4000:
        raise ValueError("Triangle budget is out of bounds")
    for key, lower, upper in (("height_m", 0.8, 8.0), ("radius_m", 0.12, 1.8)):
        number = value[key]
        if type(number) not in (float, int) or not math.isfinite(number):
            raise ValueError(f"{key} must be finite numeric")
        if not lower <= number <= upper:
            raise ValueError(f"{key} outside approved physical bounds")
    return dict(value)


def vec_sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def unit(v):
    length = math.sqrt(sum(x * x for x in v))
    if length <= 1e-9:
        raise ValueError("Degenerate generated triangle")
    return tuple(x / length for x in v)


class Surface:
    def __init__(self):
        self.positions = []
        self.normals = []
        self.texcoords = []
        self.indices = []

    def triangle(self, a, b, c, uv_a=(0, 0), uv_b=(1, 0), uv_c=(0.5, 1)):
        normal = unit(cross(vec_sub(b, a), vec_sub(c, a)))
        for p, uv in ((a, uv_a), (b, uv_b), (c, uv_c)):
            self.positions.append(p)
            self.normals.append(normal)
            self.texcoords.append(uv)
            self.indices.append(len(self.indices))

    def outward(self, a, b, c, center):
        normal = unit(cross(vec_sub(b, a), vec_sub(c, a)))
        mid = tuple((a[i] + b[i] + c[i]) / 3 for i in range(3))
        rad = (mid[0] - center[0], 0.0, mid[2] - center[2])
        if normal[0] * rad[0] + normal[2] * rad[2] < 0:
            b, c = c, b
        self.triangle(a, b, c)


def generate_geometry(spec: dict) -> list[Surface]:
    spec = validate_spec(spec)
    rng = random.Random(spec["seed"])
    materials = [Surface(), Surface()]
    target_h = float(spec["height_m"])
    radius = float(spec["radius_m"])
    count = spec["count"]
    for shard in range(count):
        angle = (2.0 * math.pi * shard / count) + rng.uniform(-0.16, 0.16)
        distance = 0.0 if shard == 0 else radius * rng.uniform(0.8, 2.15)
        centre = (math.cos(angle) * distance, 0.0, math.sin(angle) * distance)
        height = target_h * (1.0 if shard == 0 else rng.uniform(0.42, 0.86))
        width = radius * (0.82 if shard == 0 else rng.uniform(0.36, 0.73))
        sides = 6
        start = rng.uniform(0.0, math.pi / 3.0)
        surface = materials[shard % 2]
        rings = []
        for y_fraction, width_fraction in ((0.0, 0.66), (0.20, 1.0), (0.78, 0.43)):
            ring = [
                (centre[0] + math.cos(start + i * math.tau / sides) * width * width_fraction,
                 y_fraction * height,
                 centre[2] + math.sin(start + i * math.tau / sides) * width * width_fraction)
                for i in range(sides)
            ]
            rings.append(ring)
        tip = (centre[0] + math.cos(angle + 1.7) * width * 0.12,
               height, centre[2] + math.sin(angle + 1.7) * width * 0.12)
        for layer in range(len(rings) - 1):
            bottom, upper = rings[layer], rings[layer + 1]
            for j in range(sides):
                k = (j + 1) % sides
                surface.outward(bottom[j], bottom[k], upper[k], centre)
                surface.outward(bottom[j], upper[k], upper[j], centre)
        for j in range(sides):
            surface.outward(rings[-1][j], rings[-1][(j + 1) % sides], tip, centre)
            surface.triangle(centre, rings[0][(j + 1) % sides], rings[0][j])
    triangles = sum(len(surface.indices) // 3 for surface in materials)
    if triangles > spec["max_triangles"]:
        raise ValueError(f"Generated triangles ({triangles}) exceed budget ({spec['max_triangles']})")
    return materials


class BufferBuilder:
    def __init__(self):
        self.data = bytearray()
        self.views = []
        self.accessors = []

    def add(self, payload: bytes, component: int, count: int, kind: str,
            target: int, bounds=None) -> int:
        while len(self.data) % 4:
            self.data.append(0)
        offset = len(self.data)
        self.data.extend(payload)
        view = len(self.views)
        self.views.append({"buffer": 0, "byteOffset": offset, "byteLength": len(payload),
                           "target": target})
        result = {"bufferView": view, "byteOffset": 0, "componentType": component,
                  "count": count, "type": kind}
        if bounds is not None:
            result["min"], result["max"] = bounds
        self.accessors.append(result)
        return len(self.accessors) - 1


def glb_bytes(spec: dict) -> tuple[bytes, dict]:
    spec = validate_spec(spec)
    surfaces = generate_geometry(spec)
    builder = BufferBuilder()
    primitives = []
    positions_all = []
    for index, surface in enumerate(surfaces):
        n = len(surface.positions)
        if not n:
            continue
        if n >= 65535:
            raise ValueError("Per-primitive 16-bit index limit exceeded")
        positions_all.extend(surface.positions)
        coords = [v for p in surface.positions for v in p]
        lower = [min(p[i] for p in surface.positions) for i in range(3)]
        upper = [max(p[i] for p in surface.positions) for i in range(3)]
        position_id = builder.add(struct.pack("<" + "f" * len(coords), *coords), 5126, n,
                                  "VEC3", 34962, (lower, upper))
        normals = [v for p in surface.normals for v in p]
        normal_id = builder.add(struct.pack("<" + "f" * len(normals), *normals),
                                5126, n, "VEC3", 34962)
        uv = [v for p in surface.texcoords for v in p]
        uv_id = builder.add(struct.pack("<" + "f" * len(uv), *uv),
                            5126, n, "VEC2", 34962)
        indices_id = builder.add(struct.pack("<" + "H" * n, *surface.indices),
                                 5123, n, "SCALAR", 34963)
        primitives.append({"attributes": {"POSITION": position_id,
                                           "NORMAL": normal_id,
                                           "TEXCOORD_0": uv_id},
                           "indices": indices_id, "material": index, "mode": 4})
    if not positions_all:
        raise ValueError("Empty generated geometry")
    extent_min = [min(p[i] for p in positions_all) for i in range(3)]
    extent_max = [max(p[i] for p in positions_all) for i in range(3)]
    materials = [
        {"name": "Lumo_Bioluminescent_Cyan",
         "pbrMetallicRoughness": {"baseColorFactor": [0.10, 0.84, 0.92, 1.0],
                                   "metallicFactor": 0.12, "roughnessFactor": 0.31},
         "emissiveFactor": [0.06, 0.55, 0.61], "doubleSided": True},
        {"name": "Lumo_Amethyst",
         "pbrMetallicRoughness": {"baseColorFactor": [0.68, 0.32, 0.96, 1.0],
                                   "metallicFactor": 0.10, "roughnessFactor": 0.36},
         "emissiveFactor": [0.33, 0.13, 0.48], "doubleSided": True},
    ]
    gltf = {
        "asset": {"version": "2.0", "generator": "Lumo Procedural Asset Factory 1"},
        "scenes": [{"nodes": [0]}], "scene": 0,
        "nodes": [{"name": spec["asset_id"], "mesh": 0}],
        "meshes": [{"name": spec["asset_id"], "primitives": primitives}],
        "materials": materials,
        "buffers": [{"byteLength": len(builder.data)}],
        "bufferViews": builder.views, "accessors": builder.accessors,
    }
    json_raw = json.dumps(gltf, ensure_ascii=False, sort_keys=True,
                          separators=(",", ":")).encode()
    json_chunk = json_raw + b" " * ((-len(json_raw)) % 4)
    binary = bytes(builder.data)
    binary += b"\0" * ((-len(binary)) % 4)
    overall = 12 + 8 + len(json_chunk) + 8 + len(binary)
    data = (struct.pack("<4sII", b"glTF", 2, overall)
            + struct.pack("<I4s", len(json_chunk), b"JSON") + json_chunk
            + struct.pack("<I4s", len(binary), b"BIN\0") + binary)
    if len(data) != overall or len(data) > MAX_ASSET_BYTES:
        raise ValueError("Generated GLB length invalid or beyond mobile file budget")
    report = {
        "asset_id": spec["asset_id"],
        "recipe": spec["recipe"],
        "seed": spec["seed"],
        "triangles": sum(len(x.indices) // 3 for x in surfaces),
        "materials": len(materials),
        "mesh_primitives": len(primitives),
        "bbox_min_m": extent_min,
        "bbox_max_m": extent_max,
        "ground_pivot_m": extent_min[1],
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
        "spec_sha256": hashlib.sha256(json.dumps(spec, sort_keys=True).encode()).hexdigest(),
        "ai_provided_spec": False,
        "physical_device_fps_verified": False,
    }
    return data, report


def build(spec_path: Path, output_dir: Path) -> dict:
    spec = validate_spec(json.loads(spec_path.read_text(encoding="utf-8")))
    data, report = glb_bytes(spec)
    output_dir.mkdir(parents=True, exist_ok=True)
    file = output_dir / (spec["asset_id"] + ".glb")
    manifest = output_dir / (spec["asset_id"] + ".json")
    if file.is_symlink() or manifest.is_symlink():
        raise ValueError("Refusing to overwrite a symlink")
    file.write_bytes(data)
    report["file_name"] = file.name
    manifest.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n",
                        encoding="utf-8")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", required=True, type=Path)
    parser.add_argument("--output-dir", type=Path, default=Path("build/ai3d"))
    params = parser.parse_args()
    try:
        print(json.dumps(build(params.spec, params.output_dir), sort_keys=True))
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        print("LUMO_3D_FACTORY_FAILED:", exc, file=sys.stderr)
        raise SystemExit(1) from exc
